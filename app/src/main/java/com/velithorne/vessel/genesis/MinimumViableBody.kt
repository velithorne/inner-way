/**
 * Classification of the first stable living arrangement at birth (field-driven, not a pod prefab).
 */
enum class MinimumViableBody {
    /** Core knot + reserve spark; shell deferred. */
    CORE_RESERVE_SPARK,
    /** Reserve-heavy; crown latent. */
    RESERVE_FIRST,
    /** Crown tendency wins early. */
    CROWN_FIRST,
    /** Shell coherence begins to nucleate. */
    SHELL_PRESSURE_FIRST,
    /** Single lateral signal root (asymmetric). */
    SIGNAL_LATERAL_SINGLE,
    /** Strong asymmetry in the first viable graph. */
    ASYMMETRY_FIRST,
    /** Mixed / balanced genesis. */
    MIXED_COHERENCE,
}
